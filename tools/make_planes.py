#!/usr/bin/env python3
"""Create a plane CSV for any volume: a rectangle rotating 180 degrees about the volume's
vertical (index y) axis, followed by triangles sweeping along z.

    python tools/make_planes.py volume.nrrd planes.csv [--frames 48]
"""

import argparse
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from generate_dataset import fmt, rotating_rectangles, sweeping_triangles  # noqa: E402
from volproj.nrrd import read_nrrd  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("nrrd")
    parser.add_argument("csv")
    parser.add_argument("--frames", type=int, default=48)
    args = parser.parse_args()

    sx, sy, sz = read_nrrd(args.nrrd).header.sizes
    center = ((sx - 1) / 2, (sy - 1) / 2, (sz - 1) / 2)
    half = min(sx, sz) / 2 - 1
    rows = list(rotating_rectangles(center, half, (sy - 1) / 2, args.frames))
    rows += list(sweeping_triangles(np.linspace(0.1 * sz, 0.9 * sz, args.frames // 2),
                                    (sx - 1) / 2, 0, sy - 1, (sx - 1) / 2))
    with open(args.csv, "w") as f:
        f.write(f"# generated by tools/make_planes.py for {os.path.basename(args.nrrd)} {sx}x{sy}x{sz}\n")
        f.writelines(fmt(r) + "\n" for r in rows)
    print(f"wrote {args.csv} ({len(rows)} planes)")


if __name__ == "__main__":
    main()
